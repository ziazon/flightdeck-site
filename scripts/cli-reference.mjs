#!/usr/bin/env node
// Writes docs/reference/cli.md from a built `flightdeck` binary's own help, so the page lists every
// command the binary lists. Re-run it by hand at each release:
//
//   node scripts/cli-reference.mjs [path/to/flightdeck]    (default: `flightdeck` on PATH)
//
// The help is written for the people who build Flightdeck, so it carries notes about internal plans.
// This script keeps only what a user needs: each top-level command with its one-line summary (minus
// any plan or program reference), and each Jira, Slack, Trello, registry and Keychain command as its
// synopsis (the command and its flags), without the prose notes beside it. The hygiene check then
// runs over the result, and a hit fails the script.
import { execFileSync, spawnSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const out = join(root, 'docs/reference/cli.md')
const bin = process.argv[2] ?? 'flightdeck'

/** A command's help text. `link help` exits 1 after printing, so the exit code is not checked; empty output is. */
function help(...args) {
  const { stdout, error } = spawnSync(bin, args, { encoding: 'utf8' })
  if (error) throw new Error(`could not run ${bin}: ${error.message}`)
  if (!stdout.trim()) throw new Error(`${bin} ${args.join(' ')} printed nothing`)
  return stdout
}

/** Drop the references to internal plans and programs that some summaries end with. */
const summary = (text) => text
  .replace(/\s*\((?:plan §[^)]*|program [^)]*|[^()]*\bplan|the [^()]*\bagent)\)/g, '')
  .replace(/\s+/g, ' ')
  .trim()

/** Text for a table cell: pipes escaped, and `<`, `>` and `{` escaped outside code spans so Vue and HTML leave them alone. */
const cell = (text) => text
  .split(/(`[^`]*`)/)
  .map((part) => part.startsWith('`') ? part : part.replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/\{/g, '&#123;'))
  .join('')
  .replace(/\|/g, '\\|')

/** The `Commands:` section of the top-level help, as [name, summary] pairs. */
function topCommands(text) {
  const section = text.split(/^Commands:\n/m)[1]?.split(/^\S/m)[0]
  if (!section) throw new Error('no Commands: section in flightdeck --help')
  return section.split('\n')
    .map((line) => line.match(/^ {2}([a-z][a-z-]*)\s{2,}(.*)$/))
    .filter(Boolean)
    .map(([, name, about]) => [name, summary(about)])
}

/**
 * The commands `link help` lists, as synopses. An entry starts at a line `  flightdeck …`; its continuation lines are
 * indented further. A note in parentheses starts after two or more spaces, or as a continuation line of its own, and
 * runs to the end of the entry; everything before it is the synopsis.
 */
function linkCommands(text) {
  const entries = []
  let current = null
  for (const line of text.split('\n')) {
    if (/^ {2}flightdeck /.test(line)) {
      current = { synopsis: [], note: false }
      entries.push(current)
    } else if (!current || !/^ {3,}\S/.test(line)) {
      current = null
      continue
    }
    if (current.note) continue
    const trimmed = line.trim()
    if (current.synopsis.length && trimmed.startsWith('(')) { current.note = true; continue }
    const [synopsis, note] = trimmed.split(/\s{2,}\(/)
    current.synopsis.push(synopsis.trim())
    if (note !== undefined) current.note = true
  }
  return entries.map((entry) => entry.synopsis.join(' '))
}

/** Group synopses by their service: the word after `flightdeck` (`link` and `sync` together). */
function byService(synopses) {
  const titles = { link: 'Link and sync', sync: 'Link and sync', jira: 'Jira', slack: 'Slack', trello: 'Trello', terraform: 'Terraform registry', secrets: 'Keychain items' }
  const groups = new Map()
  for (const synopsis of synopses) {
    const word = synopsis.split(' ')[1]
    const title = titles[word]
    if (!title) throw new Error(`no group for \`${synopsis}\`; add its service to byService`)
    if (!groups.has(title)) groups.set(title, [])
    groups.get(title).push(synopsis)
  }
  return groups
}

const commands = topCommands(help('--help'))
const groups = byService(linkCommands(help('link', 'help')))

const page = [
  '<!-- Generated by scripts/cli-reference.mjs from `flightdeck --help` and `flightdeck link help`. Do not edit by hand. -->',
  '',
  '# Command line',
  '',
  '`flightdeck` is one program: the terminal dashboard, the daemon that keeps its state current, the link to Jira, Slack and Trello, and the job runner. `flightdeck help <command>` prints a command\'s own options.',
  '',
  '## Commands',
  '',
  '| Command | What it does |',
  '| --- | --- |',
  ...commands.map(([name, about]) => `| \`${name}\` | ${cell(about)} |`),
  '',
  '## Jira, Slack, Trello, the Terraform registry and the Keychain',
  '',
  'These commands are how agents and scripts reach your trackers and chat. Every write takes `--dry-run`, which still reads but writes nothing.',
  '',
  'Text for a comment, post or description can come from a file (`--text-file`, `--description-file`, `--desc-file`): a regular UTF-8 file of at most 64 KiB. `--markdown` renders bold, emphasis, code, lists, headings and https links. A secret goes in on stdin, never as an argument: `pbpaste | flightdeck secrets set slack`.',
  '',
  'Exit codes: 0 ok, 1 failed, 2 usage, 3 refused by a rule or an allowlist, 4 a write did not read back.',
  '',
  ...[...groups].flatMap(([title, synopses]) => [`### ${title}`, '', '```text', ...synopses, '```', '']),
].join('\n')

writeFileSync(out, page)
console.log(`cli-reference: wrote ${out} (${commands.length} commands, ${[...groups.values()].flat().length} link synopses)`)
execFileSync('bash', [join(root, 'scripts/hygiene-check.sh')], { stdio: 'inherit' })
